# build-start-here.ps1
# Aggregate the highlights of profile/ plus the latest memory file into START-HERE.md
# Usage: right-click "Run with PowerShell", or run: .\build-start-here.ps1
# Requires: PowerShell 5.1 only. No Python / Node / git dependency.
#
# ENCODING NOTE (important):
#   This file is intentionally PURE ASCII. Windows PowerShell 5.1 reads a .ps1
#   without a BOM using the system ANSI codepage (GBK on Chinese Windows), which
#   mangles any non-ASCII bytes. Keeping this file ASCII means it is byte-identical
#   under ASCII / GBK / UTF-8, so it is simultaneously:
#     - valid "UTF-8 without BOM" (acceptance rule A2), and
#     - correctly parsed by PowerShell 5.1 (acceptance rule A8).
#   All Chinese text lives in the UTF-8 (no BOM) resource files next to it:
#     start-here-header.txt / start-here-footer.txt / start-here-strings.txt
#     start-here-sections.txt
#   Do NOT type Chinese into this file. Put it in start-here-strings.txt instead.

param(
    [switch]$OpenAfter
)

$ErrorActionPreference = 'Stop'

# ---- Locate the repo root (this script lives in scripts/) ----
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$root      = Split-Path -Parent $scriptDir
$specFile  = Join-Path $scriptDir 'start-here-sections.txt'
$strFile   = Join-Path $scriptDir 'start-here-strings.txt'
$headFile  = Join-Path $scriptDir 'start-here-header.txt'
$footFile  = Join-Path $scriptDir 'start-here-footer.txt'
$outFile   = Join-Path $root 'START-HERE.md'

# ---- UTF-8 helpers ----
function Read-Utf8Lines($path) {
    return [System.IO.File]::ReadAllLines($path, [System.Text.Encoding]::UTF8)
}
function Write-Utf8($path, $text) {
    $enc = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($path, $text, $enc)
}
function Get-WordCount($text) {
    $cn = ([regex]::Matches($text, '[\u4e00-\u9fff]')).Count
    $en = ([regex]::Matches($text, '[A-Za-z0-9]+')).Count
    return ($cn + $en)
}

# ---- Load localized strings (KEY::value) ----
$Strings = @{}
if (Test-Path $strFile) {
    foreach ($l in (Read-Utf8Lines $strFile)) {
        if ([string]::IsNullOrWhiteSpace($l)) { continue }
        if ($l.Trim().StartsWith('#')) { continue }
        $i = $l.IndexOf('::')
        if ($i -lt 1) { continue }
        $Strings[$l.Substring(0, $i).Trim()] = $l.Substring($i + 2)
    }
}
function T($key) {
    if ($Strings.ContainsKey($key)) { return $Strings[$key] }
    return "[[MISSING:$key]]"
}

# ---- Header must exist ----
if (-not (Test-Path $specFile)) {
    Write-Host ((T 'MSG_NO_SPEC') -f $specFile) -ForegroundColor Red
    exit 1
}

$sb = New-Object System.Text.StringBuilder

# ================= Header =================
if (Test-Path $headFile) {
    foreach ($hl in (Read-Utf8Lines $headFile)) { [void]$sb.AppendLine($hl) }
} else {
    [void]$sb.AppendLine('# START-HERE')
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine('<!-- Generated by scripts\build-start-here.ps1 - do not edit by hand. Edit profile/ then re-run. -->')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('---')
[void]$sb.AppendLine('')

# ================= Extract by spec =================
$specLines = Read-Utf8Lines $specFile
$okCount   = 0
$missCount = 0

foreach ($line in $specLines) {
    if ([string]::IsNullOrWhiteSpace($line)) { continue }
    if ($line.Trim().StartsWith('#')) { continue }

    $parts = $line -split '\|'
    if ($parts.Count -lt 4) { continue }

    $title   = $parts[0].Trim()
    $rel     = $parts[1].Trim()
    $startRe = $parts[2].Trim()
    $endRe   = $parts[3].Trim()
    # Optional 5th column: max number of lines (0 or blank = unlimited)
    $maxLines = 0
    if ($parts.Count -ge 5) {
        $m = $parts[4].Trim()
        if ($m -match '^\d+$') { $maxLines = [int]$m }
    }

    $src = Join-Path $root $rel
    if (-not (Test-Path $src)) {
        Write-Host ((T 'MSG_SKIP_NOFILE') -f $rel) -ForegroundColor Yellow
        $missCount++
        continue
    }

    $lines   = Read-Utf8Lines $src
    $started = $false
    $hit     = 0

    # Always emit an H3 so it never collides with the source file's own H2 numbering
    if (-not [string]::IsNullOrWhiteSpace($title)) {
        [void]$sb.AppendLine("### $title")
        [void]$sb.AppendLine('')
    }

    foreach ($l in $lines) {
        if (-not $started) {
            if ($l -match $startRe) { $started = $true } else { continue }
        }
        if ($endRe -ne '__EOF__' -and $started -and $hit -gt 0 -and ($l -match $endRe)) { break }
        if ($maxLines -gt 0 -and $hit -ge $maxLines) { break }

        [void]$sb.AppendLine($l)
        $hit++
    }

    if ($hit -gt 0) {
        $okCount++
        Write-Host ((T 'MSG_OK_SECTION') -f $title, $rel, $hit) -ForegroundColor Green
        [void]$sb.AppendLine('')
    } else {
        $missCount++
        Write-Host ((T 'MSG_EMPTY_SECTION') -f $title, $rel) -ForegroundColor Yellow
    }
}

# ================= Latest memory file =================
$memDir = Join-Path $root 'memory'
if (Test-Path $memDir) {
    $months = Get-ChildItem -LiteralPath $memDir -Filter '*.md' -File |
              Where-Object { $_.Name -match '^\d{4}-\d{2}\.md$' } |
              Sort-Object Name -Descending
    if ($months.Count -gt 0) {
        $latest = $months[0]
        [void]$sb.AppendLine((T 'MSG_MEM_TITLE'))
        [void]$sb.AppendLine('')
        [void]$sb.AppendLine(((T 'MSG_MEM_FROM') -f $latest.Name))
        [void]$sb.AppendLine('')
        # Only take the entry lines inside ``` blocks, skipping headers and prose
        $body    = Read-Utf8Lines $latest.FullName
        $inBlock = $false
        $n       = 0
        foreach ($l in $body) {
            if ($l.Trim() -eq '```') {
                if ($inBlock) { $inBlock = $false } else { $inBlock = $true; continue }
                continue
            }
            if (-not $inBlock) { continue }
            if ($l.Trim() -eq '') { continue }
            if ($n -ge 3) { break }   # cap at 3 entries (keeps START-HERE within 1500-3000)
            [void]$sb.AppendLine('- ' + $l.Trim())
            $n++
        }
        if ($n -eq 0) { [void]$sb.AppendLine((T 'MSG_MEM_EMPTY')) }
        [void]$sb.AppendLine('')
        Write-Host ((T 'MSG_MEM_OK') -f $latest.Name) -ForegroundColor Green
    }
}

# ================= Footer index =================
[void]$sb.AppendLine('---')
[void]$sb.AppendLine('')
if (Test-Path $footFile) {
    foreach ($fl in (Read-Utf8Lines $footFile)) { [void]$sb.AppendLine($fl) }
}
[void]$sb.AppendLine('')

# ================= Write out =================
$text  = $sb.ToString()
Write-Utf8 $outFile $text

$bytes = (Get-Item $outFile).Length
$words = Get-WordCount $text

Write-Host ''
Write-Host (T 'MSG_DONE_TITLE') -ForegroundColor Cyan
Write-Host ((T 'MSG_DONE_FILE') -f $outFile) -ForegroundColor Cyan
Write-Host ((T 'MSG_DONE_WORDS') -f $words) -ForegroundColor Cyan
Write-Host ((T 'MSG_DONE_BYTES') -f $bytes) -ForegroundColor Cyan
Write-Host ((T 'MSG_DONE_SECTIONS') -f $okCount, $missCount) -ForegroundColor Cyan
if ($words -lt 1500) {
    Write-Host (T 'MSG_WARN_LOW') -ForegroundColor Yellow
} elseif ($words -gt 3000) {
    Write-Host (T 'MSG_WARN_HIGH') -ForegroundColor Yellow
} else {
    Write-Host (T 'MSG_OK_RANGE') -ForegroundColor Green
}
Write-Host (T 'MSG_DONE_END') -ForegroundColor Cyan

if ($OpenAfter) {
    Start-Process notepad.exe -ArgumentList $outFile
}
